import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const baselinePath = resolve(root, "supabase/production-baseline-recovery/production-baseline-2026-11-12.sql");
const outputPath = resolve(root, "docs/security/SECURITY_DEFINER_REVIEW_2026-11-22.md");
const sql = await readFile(baselinePath, "utf8");
const starts = [...sql.matchAll(/^CREATE FUNCTION\s+([^\n]+)\n/gim)].map((match) => match.index);
const functions = [];
for (let i = 0; i < starts.length; i += 1) {
  const block = sql.slice(starts[i], starts[i + 1] ?? sql.length);
  if (!/\bSECURITY\s+DEFINER\b/i.test(block)) continue;
  const identity = block.match(/^CREATE FUNCTION\s+(.+?)\s+RETURNS\s+/is)?.[1]?.replaceAll("\n", " ").replaceAll(/\s+/g, " ").trim();
  if (!identity) continue;
  const schema = identity.split(".")[0].replaceAll('"', "");
  const hasPinnedSearchPath = /\bSET\s+SEARCH_PATH\s*(?:TO|=)\s+[^\n]+/i.test(block);
  const hasAuthReference = /\bauth\.uid\s*\(\)|\bcurrent_setting\s*\(\s*['"]request\.jwt/i.test(block);
  const hasStaffGate = /has_staff_role|is_staff|admin|moderator|service_role/i.test(block);
  const isTrigger = /RETURNS\s+trigger\b/i.test(block);
  const isKnownServiceRoleBoundary = identity.startsWith("public.mort_ingest_verification_provider_event(");
  const isKnownReadOnlyRuntimeStatus = identity.startsWith("public.get_runtime_feature_status(");
  let classification = "REQUIRES FURTHER EVIDENCE";
  let reason = "Recorded baseline lacks the live ACL, owner, trigger/call graph, and current body needed for a definitive authorization conclusion.";
  if (isKnownServiceRoleBoundary) {
    classification = "SAFE (STATIC)";
    reason = "Recorded baseline ACL revokes PUBLIC and grants only service_role; the function delegates to a signature-, tenant-, freshness-, and replay-checking private ingestion boundary.";
  } else if (isKnownReadOnlyRuntimeStatus) {
    classification = "SAFE (STATIC)";
    reason = "Recorded baseline ACL revokes PUBLIC and grants authenticated/service_role; the function returns non-sensitive fail-closed runtime gates and performs no writes.";
  } else if (schema === "private" && hasPinnedSearchPath && (hasAuthReference || hasStaffGate || isTrigger)) {
    classification = "SAFE (STATIC)";
    reason = "Private-schema definer with pinned search_path and an apparent request/role/trigger boundary; live execute ACL and current production body still require confirmation.";
  } else if (!hasPinnedSearchPath || (schema === "public" && !hasAuthReference && !hasStaffGate && !isTrigger)) {
    classification = "POTENTIAL VULNERABILITY";
    reason = !hasPinnedSearchPath
      ? "SECURITY DEFINER body has no statically visible pinned search_path; search-path hijacking risk must be remediated or disproved."
      : "Public SECURITY DEFINER body has no statically visible caller/role/trigger gate; unauthorized execution must be tested and corrected if confirmed.";
  }
  functions.push({ identity, schema, classification, reason, hasPinnedSearchPath, hasAuthReference, hasStaffGate, isTrigger });
}
functions.sort((a, b) => a.identity.localeCompare(b.identity));
const counts = Object.groupBy(functions, (item) => item.classification);
const lines = [
  "# SECURITY DEFINER review — 2026-11-22",
  "",
  "> Scope: recorded production baseline `supabase/production-baseline-recovery/production-baseline-2026-11-12.sql`. This is an offline source review, not hosted production verification. The production advisor's 70 authenticated-callable count must be reconciled against a fresh read-only catalog export when authorized credentials are available.",
  "",
  `- Functions extracted: **${functions.length}** SECURITY DEFINER definitions`,
  `- Safe (static): **${(counts["SAFE (STATIC)"] ?? []).length}**`,
  `- Potential vulnerability: **${(counts["POTENTIAL VULNERABILITY"] ?? []).length}**`,
  `- Requires further evidence: **${(counts["REQUIRES FURTHER EVIDENCE"] ?? []).length}**`,
  "",
  "## Review rule",
  "",
  "Static classification is intentionally conservative. `SAFE (STATIC)` does not mean production-safe: it requires current ACL/owner evidence, authenticated persona tests, and call-graph review. `POTENTIAL VULNERABILITY` is a remediation queue, not a claim that exploitation was proven. No production change is generated by this report.",
  "",
  "## Individual inventory",
  "",
  "| # | Function | Classification | Static signals | Evidence / next action |",
  "|---:|---|---|---|---|",
];
for (const [index, item] of functions.entries()) {
  const signals = [
    item.hasPinnedSearchPath ? "pinned search_path" : "NO pinned search_path",
    item.hasAuthReference ? "auth reference" : "no auth reference",
    item.hasStaffGate ? "role/staff signal" : "no role signal",
    item.isTrigger ? "trigger" : "callable/body",
  ].join("; ");
  lines.push(`| ${index + 1} | \`${item.identity}\` | **${item.classification}** | ${signals} | ${item.reason} |`);
}
lines.push(
  "",
  "## Required hosted reconciliation",
  "",
  "1. Run `scripts/audit-db-security-remote.mjs` against the authorized QA project only, never production, and export schema, identity arguments, owner, `prosecdef`, `proconfig`, ACL, and trigger references.",
  "2. Reconcile the live authenticated-callable set to this baseline inventory and explain additions/removals/drift.",
  "3. For every potential vulnerability, reproduce with anon, authenticated non-owner, wrong-role staff, suspended, blocked, and owner personas using real QA sessions; do not use synthetic JWT claims.",
  "4. Remediate only confirmed defects in forward-only QA-first migrations and add regression coverage before requesting production approval.",
  "",
);
await writeFile(outputPath, lines.join("\n"));
console.log(`Wrote ${outputPath}`);
console.log(`Extracted ${functions.length}; safe-static ${(counts["SAFE (STATIC)"] ?? []).length}; potential ${(counts["POTENTIAL VULNERABILITY"] ?? []).length}; further ${(counts["REQUIRES FURTHER EVIDENCE"] ?? []).length}`);

export interface SupportEvaluationCase {
  caseKey: string;
  message: string;
  expectedIntent: string;
  expectedLevel: number;
}

function cases(
  prefix: string,
  messages: string[],
  expectedIntent: string,
  expectedLevel: number,
): SupportEvaluationCase[] {
  return messages.map((message, index) => ({
    caseKey: `${prefix}_${String(index + 1).padStart(2, "0")}`,
    message,
    expectedIntent,
    expectedLevel,
  }));
}

